'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
require('../js/phonemes.js');
require('../js/g2p.js');

const source = 'https://raw.githubusercontent.com/PyThaiNLP/thai-g2p-wiktionary-corpus/3c96f5e948a64b8262be78fa98beecf1d43b1965/wiktionary-23-7-2022-clean.tsv';
const sha256 = 'abc9cadc33caf3f031299ec1d3588513505bfc2fdbecff004d10ee02998387a6';

async function main() {
  let input;
  if (process.argv[2]) input = fs.readFileSync(process.argv[2]);
  else {
    const response = await fetch(source);
    if (!response.ok) throw new Error('Thai dictionary download failed: ' + response.status);
    input = Buffer.from(await response.arrayBuffer());
  }
  if (crypto.createHash('sha256').update(input).digest('hex') !== sha256) {
    throw new Error('Thai dictionary source checksum mismatch');
  }
  const dictionary = Object.create(null);
  for (const line of input.toString('utf8').split(/\r?\n/)) {
    const [word, ipa] = line.split('\t');
    if (!/^[ก-ฺเ-๎]+$/.test(word) || !ipa || dictionary[word]) continue;
    const reading = global.NSG.thaiIPA(ipa);
    if (!reading || !reading.every(syllable => syllable.tone &&
      syllable.phones.every(id => Object.hasOwn(global.NSG.PHONES, id)))) continue;
    dictionary[word] = reading.map(syllable =>
      [syllable.phones.join(' '), syllable.tone, syllable.vowelLength[0]].join(':')).join('/');
  }
  const notice = '/* Thai pronunciation data by Wiktionary contributors, extracted by PyThaiNLP.\n' +
    ' * CC BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/).\n' +
    ' * Source: ' + source + '\n' +
    ' * Converted to NSG phonemes. Attribution and changes: assets/licenses/thai-dictionary.md.\n' +
    ' * Generated by scripts/build-thai-dictionary.js. */\n';
  const rows = Object.entries(dictionary).map(([word, value]) => JSON.stringify(word) + ':' + JSON.stringify(value));
  fs.writeFileSync(path.join(__dirname, '../js/data/th.js'), notice +
    '(function (r) {\n  r.NSG_DICT = r.NSG_DICT || {};\n  r.NSG_DICT.th = {\n' +
    rows.map(row => '    ' + row).join(',\n') + '\n  };\n})(typeof window !== "undefined" ? window : global);\n');
  console.log('Thai pronunciation entries: ' + rows.length);
}

main().catch(error => { console.error(error); process.exitCode = 1; });
