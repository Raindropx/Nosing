'use strict';
// Reproducible offline compiler. The CSV is CC BY-SA Wiktionary data; no CANTOR
// dictionary or binaries are used. See assets/licenses/german-dictionary.md.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
require('../js/phonemes.js'); require('../js/g2p.js');
const source = 'https://raw.githubusercontent.com/devio-at/german-ipa-dict/a08113e0ab80f049b625fc360196491f56243ca1/de_enwikt.csv';
const sha256 = 'fbe9e3370cd711a4feb9211987483d0ec55b776a2101170f3ff9aa5b729dbae2';
function csv(line) {
  const out = []; let quoted = false, field = '';
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c === '"') { if (quoted && line[i + 1] === '"') { field += '"'; i++; } else quoted = !quoted; }
    else if (c === ',' && !quoted) { out.push(field); field = ''; }
    else field += c;
  }
  return out.concat(field);
}
async function main() {
  const input = process.argv[2] ? fs.readFileSync(process.argv[2]) : Buffer.from(await (await fetch(source)).arrayBuffer());
  if (crypto.createHash('sha256').update(input).digest('hex') !== sha256) throw Error('German source checksum mismatch');
  const dict = Object.create(null), ranks = Object.create(null); let skipped = 0;
  for (const line of input.toString('utf8').split(/\r?\n/)) {
    const row = csv(line), word = row[0].normalize('NFC'), key = word.toLowerCase();
    if (!/^[a-zäöüßéèêëàáâîïôûùç]+(?:[-'][a-zäöüßéèêëàáâîïôûùç]+)*$/i.test(word) || !row[1]) continue;
    const ipaField = row[1].split(/<ref|&lt;ref/i)[0];
    // Skip hyphenated partial-fragment rows like "/ˈiːs-/,/-tam-/,/ˌbʊl/" or "[ˌ-vɔɐ̯t]".
    const matches = [...ipaField.matchAll(/\/([^/]+)\/|\[([^\]]+)\]/g)];
    if (!matches.length) continue;
    const label = row.slice(2).join(' ').toLowerCase();
    const hasStandard = /\bstandard\b/.test(label);
    const isFrag = s => /^\s*[ˈˌ.\-]*-|-\s*$|…/.test(s);
    const hasFragmentSibling = matches.some(m => isFrag(m[1] || m[2]));
    const monoCodaR = /^[bcdfghjklmnpqrstvwxzß]*(?!ei|ai|ey|ay|au|eu|äu)[aeiouyäöü]{1,2}h?r$/i.test(word);
    const candidates = [];
    for (const match of matches) {
      let rawIpa = match[1] || match[2];
      if (isFrag(rawIpa) || hasFragmentSibling) continue;
      if (monoCodaR) rawIpa = rawIpa.replace(/([aɑäiɪeɛoɔuʊyʏøœ][ːˑ]?)ɐ(?!\u032f)$/, '$1ɐ\u032f');
      const groups = global.NSG.germanIPA(rawIpa);
      if (!groups) { skipped++; continue; }
      candidates.push({ groups, isSlash: !!match[1] });
    }
    const maxSyl = candidates.reduce((m, c) => Math.max(m, c.groups.length), 0);
    for (const c of candidates) {
      // Penalize truncated rhyme/stem slashes like "/kʊnst/,[ˈhantvɛʁks.kʰʊnst]" when a fuller sibling exists.
      const truncated = candidates.length > 1 && c.groups.length === 1 && maxSyl >= 3;
      const rank = (word === key ? 3 : 0) + (c.isSlash ? 2 : 0) - (truncated ? 20 : 0) +
        (/official standard|prescriptive standard/.test(label) ? 30 : hasStandard ? 5 : 0) -
        (!hasStandard && /bavaria|austria|switzerland/.test(label) ? 10 : 0) -
        (/colloquial|dialect|common speech|informal|obsolete|archaic|in numbers|alternative de-facto|fast speech|casual/.test(label) ? 10 : 0);
      if (ranks[key] === undefined || rank > ranks[key]) {
        dict[key] = c.groups.map(p => p.join(' ')).join('/'); ranks[key] = rank;
      }
    }
  }
  for (const word of Object.keys(dict)) {
    const alias = word.replace(/ä/g, 'ae').replace(/ö/g, 'oe').replace(/ü/g, 'ue').replace(/ß/g, 'ss');
    if (!dict[alias]) dict[alias] = dict[word];
  }
  const ordered = Object.fromEntries(Object.keys(dict).sort().map(k => [k, dict[k]]));
  const notice = '/* German pronunciation lexicon, derived from Wiktionary via devio-at/german-ipa-dict.\n' +
    ' * CC BY-SA; attribution, source revision and conversion details: assets/licenses/german-dictionary.md.\n' +
    ' * Generated by scripts/build-german-dictionary.js. Do not edit manually. */\n';
  fs.writeFileSync(path.join(__dirname, '../js/data/de.js'), notice +
    '(function(r){r.NSG_DICT=r.NSG_DICT||{};r.NSG_DICT.de=' + JSON.stringify(ordered) +
    ';})(typeof window!=="undefined"?window:global);\n');
  console.log(JSON.stringify({ entries: Object.keys(dict).length, unsupportedRows: skipped, source, sha256 }));
}
main().catch(e => { console.error(e); process.exitCode = 1; });
